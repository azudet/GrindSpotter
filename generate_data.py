#!/usr/bin/env python3
"""
generate_data.py - Compiles camps.json into Data.lua for GrindSpotter (WoW Classic Era 1.15.x)
"""

import json
import os

def format_lua_string(val):
    val_clean = str(val).replace('\\', '\\\\').replace('"', '\\"')
    return f'"{val_clean}"'

def format_number(val):
    """
    Format numeric values cleanly without scientific notation or loss of precision on small drop rates.
    E.g. 0.005 -> 0.005, 0.45 -> 0.45, 1.0 -> 1.0, 52.0 -> 52.0
    """
    f = float(val)
    # Format up to 6 decimal places and strip trailing zeros after decimal
    formatted = f"{f:.6f}".rstrip("0").rstrip(".")
    if "." not in formatted:
        formatted += ".0"
    return formatted

def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    json_path = os.path.join(script_dir, "camps.json")
    output_path = os.path.join(script_dir, "Data.lua")

    if not os.path.exists(json_path):
        print(f"Error: {json_path} does not exist.")
        return

    with open(json_path, "r", encoding="utf-8") as f:
        camps = json.load(f)

    lines = []
    lines.append("-- Auto-generated by generate_data.py for GrindSpotter (WoW Classic Era 1.15.x)")
    lines.append("-- Do not edit directly; modify camps.json / generate_data.py and re-run.")
    lines.append("")
    lines.append("GrindSpotterData = GrindSpotterData or {}")
    lines.append("GrindSpotterData.version = 1")
    lines.append("GrindSpotterData.camps = {")

    for camp in camps:
        lines.append("    {")
        lines.append(f"        id = {format_lua_string(camp['id'])},")
        lines.append(f"        name = {format_lua_string(camp['name'])},")
        lines.append(f"        creatureEntry = {int(camp.get('creatureEntry', 0))},")
        lines.append(f"        mapID = {int(camp['mapID'])},")
        lines.append(f"        zone = {format_lua_string(camp['zone'])},")
        lines.append(f"        x = {float(camp['x']):.2f},")
        lines.append(f"        y = {float(camp['y']):.2f},")
        lines.append(f"        minLevel = {int(camp['minLevel'])},")
        lines.append(f"        maxLevel = {int(camp['maxLevel'])},")
        lines.append(f"        faction = {format_lua_string(camp['faction'])},")
        lines.append(f"        density = {format_lua_string(camp['density'])},")
        lines.append(f"        respawnMin = {float(camp['respawnMin']):.1f},")
        lines.append(f"        isQuestMob = {'true' if camp.get('isQuestMob') else 'false'},")

        tag_strs = [format_lua_string(t) for t in camp.get("tags", [])]
        lines.append(f"        tags = {{ {', '.join(tag_strs)} }},")

        lines.append("        drops = {")
        for item, rate in camp.get("drops", {}).items():
            formatted_rate = format_number(rate)
            lines.append(f"            [{format_lua_string(item)}] = {formatted_rate},")
        lines.append("        },")
        lines.append("    },")

    lines.append("}")
    lines.append("")

    with open(output_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"Successfully generated {output_path} with {len(camps)} camps.")

if __name__ == "__main__":
    main()

